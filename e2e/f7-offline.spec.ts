import { expect, test } from "@playwright/test";
import { armOffline, settle, signUp, watch } from "./helpers.ts";

test("the quote, invoice, and payment survive offline and sync once", async ({ page }) => {
  const errors = watch(page);
  await armOffline(page);
  await signUp(page);
  await settle(page);
  await page.context().setOffline(true);
  await expect(page.getByRole("status")).toHaveText("On this phone");
  await page.getByRole("link", { name: "New quote" }).click();
  await page.getByLabel("Customer").fill("Rosa Alvarez");
  const line = page.getByRole("group", { name: "Line 1" });
  await line.getByLabel("Description").fill("Replace the kitchen faucet");
  await line.getByLabel("Qty").fill("1");
  await line.getByLabel("Price").fill("20.00");
  await page.getByRole("button", { name: "Save quote" }).click();
  await expect(page.getByRole("heading", { name: /Q-\d+/ })).toBeVisible();
  await page.getByRole("button", { name: "Mark approved" }).click();
  await page.getByRole("button", { name: "Make invoice" }).click();
  await expect(page.getByRole("heading", { name: /INV-\d+/ })).toBeVisible();
  await page.getByRole("button", { name: "Mark paid" }).click();
  await expect(page.getByText("Paid in full.")).toBeVisible();
  await page.context().setOffline(false);
  await settle(page);
  await page.reload();
  await expect(page.getByText("Paid in full.")).toBeVisible();
  const first = await page.request.get("/api/sync");
  const body = (await first.json()) as { quotes: unknown[]; invoices: { status: string }[]; invoicesLength?: number };
  const snap = body as { quotes: unknown[]; invoices: { status: string; payments: unknown[] }[] };
  expect(snap.quotes).toHaveLength(1);
  expect(snap.invoices).toHaveLength(1);
  expect(snap.invoices[0].status).toBe("paid");
  expect(snap.invoices[0].payments).toHaveLength(1);
  await page.getByRole("link", { name: "Today" }).click();
  await settle(page);
  const second = (await (await page.request.get("/api/sync")).json()) as { quotes: unknown[]; invoices: { payments: unknown[] }[] };
  expect(second.quotes).toHaveLength(1);
  expect(second.invoices).toHaveLength(1);
  expect(second.invoices[0].payments).toHaveLength(1);
  expect(errors).toEqual([]);
});
